"""Compiles the mod's shaders (src/shaders/*.hlsl, entry main; ps_5_0, or vs_5_0 for files named *_vs.hlsl)
with Windows' d3dcompiler_47 and writes src/shaders_gen.h: one byte array per shader, named g_sh_<file name>.
The DXBC is embedded so the mod never needs a shader compiler at run time (Wine's or Android's).
Usage: python compile_shaders.py <src dir>"""
import ctypes
import glob
import os
import sys

src = sys.argv[1]
d3dc = ctypes.WinDLL('d3dcompiler_47.dll')


def blob_bytes(b):
    vt = ctypes.cast(ctypes.cast(b, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    getp = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])
    gets = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])
    return ctypes.string_at(getp(b), gets(b))


out = ['/* generated by tools/compile_shaders.py from src/shaders: do not edit */', '#pragma once', '']
for path in sorted(glob.glob(os.path.join(src, 'shaders', '*.hlsl'))):
    text = open(path, 'rb').read()
    code, err = ctypes.c_void_p(), ctypes.c_void_p()
    target = b'vs_5_0' if path.endswith('_vs.hlsl') else b'ps_5_0'
    hr = d3dc.D3DCompile(text, len(text), os.path.basename(path).encode(), None, None, b'main', target,
                         1 << 15, 0, ctypes.byref(code), ctypes.byref(err))  # D3DCOMPILE_OPTIMIZATION_LEVEL3
    if hr != 0:
        msg = blob_bytes(err).decode('latin1') if err.value else hex(hr & 0xFFFFFFFF)
        sys.exit(f'{path}: {msg}')
    data = blob_bytes(code)
    name = 'g_sh_' + os.path.splitext(os.path.basename(path))[0]
    out.append(f'static const unsigned char {name}[{len(data)}] = {{')
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    out.append('};')
    print(f'{os.path.basename(path)}: {len(data)} bytes')
open(os.path.join(src, 'shaders_gen.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
